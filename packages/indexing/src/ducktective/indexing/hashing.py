import hashlib

from ducktective.core.types import (
    ContentHash,
)


def content_hash(text: str) -> ContentHash:
    """Хеш содержимого — основа инкрементальности.

    Совпадение хеша означает, что разбирать файл заново и считать для его
    чанков эмбеддинги не нужно.
    """
    return ContentHash(hashlib.sha256(text.encode("utf-8")).hexdigest())


CHARACTERS_PER_TOKEN = 3.0
"""Сколько символов кода приходится на токен.

Измерено на 25 фрагментах этого репозитория против `google/gemma-4-e4b`:
в среднем 3.17 символа на токен, медиана 3.15, минимум 2.24.

Делитель взят меньше среднего намеренно. Оценка нужна для упаковки контекста
под бюджет, а там ошибки несимметричны: завышение оставляет место
неиспользованным, занижение приводит к тому, что собранное не влезает
и обрезается на стороне модели. Прежнее значение 4 занижало длину
в 24 случаях из 25, до 44% в худшем.
"""


def estimate_tokens(text: str) -> int:
    """Оценка длины в токенах без обращения к модели.

    Настоящий токенизатор привязал бы индексацию к конкретной модели и
    потребовал бы её файлов на машине, что несовместимо с air-gapped
    профилем. Точность оценки — около 11% при систематическом запасе вверх.
    """
    return max(1, round(len(text) / CHARACTERS_PER_TOKEN))
